param(
    [Parameter(Mandatory)][string]$ProjectFile,[string]$EngineRoot = 'C:/Program Files/Epic Games/UE_5.7')
$ErrorActionPreference = 'Stop'
$ProjectFile = (Resolve-Path -LiteralPath $ProjectFile).Path
if ([IO.Path]::GetExtension($ProjectFile) -ne '.uproject' -or -not (Test-Path -LiteralPath $ProjectFile -PathType Leaf)) { throw 'ProjectFile must be an existing .uproject file.' }
$projectRoot = Split-Path -Parent $ProjectFile
$reportDirectory = Join-Path $projectRoot 'Saved/BlueprintWorkbench'
New-Item -ItemType Directory -Force -Path $reportDirectory | Out-Null
foreach ($scriptName in @('TestWorkbench', 'TestWorkbenchReload')) {
    & (Join-Path $EngineRoot 'Engine/Binaries/Win64/UnrealEditor-Cmd.exe') `
        $ProjectFile -run=pythonscript `
        "-script=$PSScriptRoot/$scriptName.py" -unattended -nop4 -NullRHI -nosound `
        "-abslog=$reportDirectory/$scriptName.log"
    if ($LASTEXITCODE -ne 0) { throw "$scriptName failed; see $reportDirectory/$scriptName.log" }
}
$reportFile = Join-Path $reportDirectory 'test-results.json'
$report = Get-Content -LiteralPath $reportFile -Raw | ConvertFrom-Json
if ($report.run_id -notmatch '^[a-f0-9]{32}$') { throw 'Invalid test run identity.' }
$expected = [IO.Path]::GetFullPath((Join-Path $projectRoot "Content/__BlueprintWorkbenchTests/$($report.run_id)/BP_Patched.uasset"))
if ([IO.Path]::GetFullPath($report.fixture_file) -ne $expected) { throw 'Unexpected test cleanup path.' }
# Only the exact package generated by this run, after both UE processes have exited; no recursive deletion.
Remove-Item -LiteralPath $expected
$testDirectory = Split-Path -Parent $expected
if (@(Get-ChildItem -LiteralPath $testDirectory -Force).Count -eq 0) { Remove-Item -LiteralPath $testDirectory }
$report.checks += 'generated test asset removed after round-trip verification'
$report | ConvertTo-Json -Depth 10 | Set-Content -LiteralPath $reportFile -Encoding UTF8
Write-Output "Blueprint Workbench: $($report.checks.Count) checks passed. Report: $reportFile"
